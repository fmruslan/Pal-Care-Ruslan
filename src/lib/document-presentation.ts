import type { CareDocument } from "../db/schema";
import { demoData } from "./demo/fixtures";
import { findTwin, displayDate, money } from "./demo/presentation";
import { tenProductPack, withTenProductFixtures } from "./care/demo/catalog";
import {
  consumerDemoDocuments,
  consumerDemoSources,
} from "./care/demo/consumer-evidence";
import { demoMerchantPolicy } from "./commerce/contracts";
import type { DocumentView } from "./document-view";

const known = withTenProductFixtures(demoData);
const originalDocuments = [...known.documents, ...consumerDemoDocuments];
type Record = NonNullable<ReturnType<typeof findTwin>>;
export function documentPresentation(
  document: CareDocument,
  record: Record,
  asOf = new Date().toISOString(),
): DocumentView {
  const view: DocumentView = {
    title: `${record.product.name} · saved record`,
    provenance:
      document.origin === "sandbox" ? "PayPal Sandbox record" : "Illustrative",
    status: "Summary unavailable",
    facts: [],
    sections: [],
    next: "Open the original record or download a copy to read its contents.",
    limitation:
      "This document’s format or purchase details could not be verified for a readable summary.",
    recognized: false,
    actions: [],
  };
  const fact = (label: string, value: string) =>
    view.facts.push({ label, value });
  const section = (title: string, ...items: string[]) =>
    view.sections.push({ title, items });
  if (document.twinId !== record.twin.id || !Number.isFinite(Date.parse(asOf)))
    return view;
  const original = originalDocuments.find((d) => d.id === document.id);
  const expectedTwin = known.twins.find((t) => t.id === document.twinId);
  const exactExample =
    original &&
    expectedTwin &&
    document.origin === "sample" &&
    record.twin.origin === "sample" &&
    document.kind === original.kind &&
    document.title === original.title &&
    document.content === original.content &&
    original.twinId === document.twinId &&
    expectedTwin.productId === record.twin.productId &&
    expectedTwin.currency === record.twin.currency &&
    expectedTwin.productId === record.product.id &&
    expectedTwin.purchasePriceMinor === record.twin.purchasePriceMinor &&
    expectedTwin.purchasedOn === record.twin.purchasedOn &&
    known.products.some(
      (p) =>
        p.id === record.product.id &&
        p.currency === record.product.currency &&
        p.name === record.product.name &&
        p.brand === record.product.brand &&
        p.model === record.product.model,
    );
  // Sandbox receipts must match the generated format and their original capture,
  // amount, product snapshot and dates. A kind/title alone is never payment proof.
  const twin = record.twin,
    product = record.product;
  const sandbox =
    twin.origin === "sandbox" &&
    twin.productSnapshot &&
    twin.currency === "USD" &&
    twin.productSnapshot.currency === "USD" &&
    twin.productSnapshot.id === twin.productId &&
    product.id === twin.productId &&
    twin.checkoutOrderId &&
    twin.paypalOrderId &&
    twin.paypalCaptureId &&
    twin.verifiedAt;
  const receiptMatch = document.content.match(
    /^PAL CARE — VERIFIED PAYPAL SANDBOX RECEIPT\nFictional product: (.+)\nDemo merchant: (.+)\nSandbox total: USD (\d+\.\d{2})\nPayPal Sandbox order: ([A-Z0-9]+)\nPayPal Sandbox capture: ([A-Z0-9]+)\nCapture timestamp: ([^\n]+)\nServer verified: ([^\n]+)\n\nGenerated by Pal Care from a retrieved, validated PayPal Sandbox capture\. Simulated money only; not a real-money receipt, tax invoice, warranty or insurance\. No payer identity is stored\.$/,
  );
  const exactReceipt =
    sandbox &&
    document.origin === "sandbox" &&
    document.kind === "receipt" &&
    document.title === `${product.name} · sandbox receipt`.slice(0, 120) &&
    receiptMatch &&
    receiptMatch[1] === `${product.brand} ${product.name} (${product.model})` &&
    receiptMatch[2] === twin.productSnapshot!.merchantName &&
    receiptMatch[3] === (twin.purchasePriceMinor / 100).toFixed(2) &&
    receiptMatch[4] === twin.paypalOrderId &&
    receiptMatch[5] === twin.paypalCaptureId &&
    Number.isFinite(Date.parse(receiptMatch[6])) &&
    receiptMatch[6].slice(0, 10) === twin.purchasedOn &&
    Date.parse(receiptMatch[7]) === Date.parse(twin.verifiedAt!);
  const exactPolicy =
    sandbox &&
    document.origin === "sample" &&
    document.kind === "policy" &&
    document.title === demoMerchantPolicy.title &&
    document.content === demoMerchantPolicy.content;
  if (!exactExample && !exactReceipt && !exactPolicy) return view;
  view.recognized = true;
  view.next = "";
  view.limitation =
    "Fictional example. No actual merchant action or payment occurred.";
  if (document.kind === "receipt") {
    view.title = `${product.name} receipt`;
    view.status = exactReceipt
      ? "Payment verified in PayPal Sandbox"
      : "Purchase recorded";
    view.provenance = exactReceipt
      ? "PayPal Sandbox · Verified"
      : "Illustrative";
    fact("Product", `${product.brand} ${product.name} · ${product.model}`);
    fact(
      "Merchant",
      twin.productSnapshot?.merchantName ?? demoData.merchant.name,
    );
    fact("Purchase date", displayDate(twin.purchasedOn));
    fact(
      exactReceipt ? "Sandbox amount" : "Purchase value",
      money(twin.purchasePriceMinor),
    );
    view.limitation = exactReceipt
      ? "Completed test payment, not a real-money receipt. No goods were shipped."
      : "Example receipt. No payment was processed.";
    return view;
  }
  if (exactPolicy) {
    view.title = `${product.name} purchase terms`;
    view.provenance = "Illustrative terms · Sandbox purchase";
    view.status = "No coverage or refund promise";
    section(
      "Saved terms",
      "Fictional goods; nothing ships.",
      "No real warranty, insurance or coverage.",
      "No automated price adjustment or refund is offered by these terms.",
    );
    view.limitation =
      "These demonstration terms apply to this saved Sandbox purchase, not real commerce.";
    return view;
  }
  const consumer = consumerDemoSources.find(
    (s) => s.documentId === document.id,
  );
  if (consumer) {
    if (consumer.kind === "return-progress") {
      view.title = "Boots return progress";
      view.status = "Inspection pending";
      section("Return history", ...consumer.milestones);
      section("Refund", "No refund confirmed.");
      view.next =
        "Keep the return confirmation and parcel receipt while awaiting the inspection result.";
      view.limitation =
        "Example return scenario. No actual merchant return or PayPal refund occurred.";
    } else if (consumer.kind === "price-opportunity") {
      view.title = "Headphones price comparison";
      view.status = "Lower example catalog price";
      fact("Purchase value", money(consumer.paidMinor));
      fact("Reference price", money(consumer.currentMinor));
      fact("Difference", money(consumer.paidMinor - consumer.currentMinor));
      fact("Saved on", displayDate(consumer.asOf));
      view.next =
        "Check the seller’s price-adjustment policy and deadline before requesting an adjustment.";
      view.limitation =
        "Illustrative price comparison, not a current quote, confirmed eligibility or money saved.";
    } else {
      view.title = "Book refund example";
      view.status = "No PayPal refund confirmed";
      fact("Illustrated amount", money(consumer.amountMinor));
      fact("Example completion date", displayDate(consumer.completedOn));
      section(
        "Recorded sequence",
        "The example marks the refund as completed.",
        "No provider-verified refund accompanies this record.",
      );
      view.limitation =
        "Fictional refund scenario. No PayPal refund was issued; this amount is not money recovered.";
    }
    return view;
  }
  const s = tenProductPack.scenarios.find((s) => s.documentId === document.id);
  if (s) {
    const before = "startsAt" in s && Date.parse(asOf) < Date.parse(s.startsAt);
    const ended = "endsAt" in s && Date.parse(asOf) >= Date.parse(s.endsAt);
    if (s.kind === "return-window") {
      view.title = `${product.name} return`;
      view.status = before
        ? "Window not started"
        : ended
          ? "Window ended"
          : "Return window open";
      fact("Return deadline", `${displayDate(s.endsAt)}, noon UTC`);
      if (s.requiresUnopened)
        section(
          "Saved conditions",
          "Unopened physical Switch game required; opened and digital copies excluded.",
          "Original receipt and seller acceptance required.",
        );
      else
        section(
          "Saved conditions",
          "Clean condition and original proof required.",
          "$20 restocking charge.",
        );
      fact(
        "Item condition",
        s.condition === "unknown" ? "Not recorded" : "Unopened",
      );
      fact("Seller acceptance", "Not confirmed");
      view.next = ended
        ? "Contact the seller about any exceptions if you still need to return the item."
        : "Check the item’s condition and contact the seller before the deadline.";
      view.limitation =
        "Illustrative Everyday Goods terms, not the retailer’s or manufacturer’s actual return policy.";
    } else if (s.kind === "warranty") {
      view.title = `${product.name} warranty terms`;
      view.status = before
        ? "Term not started"
        : ended
          ? "Term ended"
          : "Recorded warranty term";
      fact("Starts", displayDate(s.startsAt));
      fact("Ends", displayDate(s.endsAt));
      if (s.extended) {
        fact("Base term ends", "Oct 20, 2027");
        section("Coverage", "Mechanical faults only.");
        section("Exclusions", "Misuse and consumables.");
      } else if (product.illustration === "boots") {
        section("Coverage", "Stitching defects.");
        section("Exclusions", "Ordinary wear and water damage.");
      } else {
        section("Coverage", "Defects only.");
        section("Exclusions", "Accidental damage.");
      }
      view.next =
        "Check the seller’s actual warranty before arranging a repair.";
      view.limitation =
        "Illustrative warranty terms for this purchase only. No real manufacturer coverage is established.";
    } else if (s.kind === "delivery") {
      view.title = `${product.name} delivery`;
      view.status = "Delivery unconfirmed";
      fact("Estimated arrival", displayDate(s.estimatedAt));
      section(
        "Saved updates",
        ...s.updates.map(
          (u) =>
            `${displayDate(u.at)} · ${{ prepared: "Prepared", dispatched: "Dispatched", "in-transit": "In transit" }[u.status]}`,
        ),
      );
      view.next =
        "Check the seller’s shipping confirmation for a tracking link.";
      view.limitation =
        "Illustrative delivery updates. No live tracking or confirmed arrival.";
    } else if (s.kind === "safety") {
      view.title = `${product.name} safety review`;
      view.status = "No official recall match established";
      section(
        "Check before acting",
        `Match ${product.brand} ${product.model} and the batch or serial number against an official recall notice.`,
      );
      view.next =
        "Review the linked safety page for official sources and product-matching requirements.";
      view.actions = [
        { label: "Review safety sources", href: `/safety?twinId=${twin.id}` },
      ];
      view.limitation =
        "Illustrative notice, not an official recall or a safety all-clear. The reviewed Insignia notice concerns a different product.";
    } else if (s.kind === "gap") {
      view.title = `${product.name} coverage record`;
      view.status = "No coverage terms saved";
      section(
        "Available evidence",
        "A receipt is saved for this hardcover book.",
        "The comparable paperback listing does not establish coverage for this edition.",
      );
      view.next = "Ask the seller for the terms that apply to this purchase.";
    } else {
      view.title = `${product.name} price checks`;
      view.status = before
        ? "Review not started"
        : ended
          ? "Review window ended"
          : "Saved price checks";
      fact("Review deadline", `${displayDate(s.endsAt)}, noon UTC`);
      fact("Hypothetical purchase amount", money(s.hypotheticalPurchaseMinor));
      section(
        "Recorded prices",
        ...s.observations.map(
          (o) =>
            `${displayDate(o.at)} · ${money(o.priceMinor)} · ${o.variant.replace("demo catalog", "example catalog")}`,
        ),
      );
      if (twin.purchasePriceMinor === 0)
        fact("Actual purchase amount", "Not recorded");
      view.next =
        "Compare the exact model and seller’s policy using the original receipt.";
      view.limitation =
        "Illustrative catalog checks, not live price monitoring, adjustment eligibility or savings.";
    }
    return view;
  }
  if (document.id.endsWith("000303")) {
    view.title = "Speaker care document";
    view.status = "Manufacturer instructions missing";
    section(
      "What’s saved",
      "This care card contains no verified instructions for Forma F-03.",
    );
    view.next =
      "Find the manufacturer’s manual for the exact model before following cleaning, charging or repair advice.";
    view.limitation = "Illustrative care card, not a manufacturer manual.";
  } else {
    view.title = "Raspberry Pi 5 ownership note";
    view.status = "Purchase price not recorded";
    section(
      "Available guidance",
      "Official Raspberry Pi Ltd documentation is available in Product care, with exact-model guidance and source attribution.",
    );
    view.next = "Open Product care for setup, power and cooling guidance.";
    view.actions = [
      { label: "Open Product care", href: `/vault/${twin.id}/care` },
    ];
    view.limitation =
      "Illustrative ownership record. No payment or receipt is claimed; the zero placeholder is not a product price.";
  }
  return view;
}
